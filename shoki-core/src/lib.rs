//! shoki の純粋な層（`core`）。
//!
//! **この層は I/O もスレッドも UI も持たない。** 持つのは状態（`AppState`）・判断
//! （`update` / `Effect`）・状態から文言への表だけで、外の世界に触るのはすべて `shoki` 側
//! （`shell`）の仕事。
//!
//! ```text
//! shell（副作用がある層）
//!   UI（Slint 配線）／ job runtime ／ adapters
//!         ↓ Command / Event        ↑ Effect / View
//! core（このクレート）
//!   update(&mut AppState, Msg) -> Vec<Effect>
//!   view_*(&AppState) -> ...
//! ```
//!
//! **なぜ分けるか**: 「セッション X のいまの状態は何か」に答える関数が `shoki` 側に 6 つあり、
//! それぞれ独自の優先順位を持っていた。#178 / #182 / #175 / #176 は 4 本連続で同じ形の
//! バグ——「本番だけが通る 1 行が、テストから呼べない位置にある」——を出している。状態を持つ
//! 場所を 1 つにし、判断を副作用から引き剥がすことで、その形を構造的に消す。
//!
//! **向きを守るのはクレート境界**。`shoki-core` は `shoki` に依存しないので、ここから
//! ディスクを読むコードはコンパイルが通らない。事実は adapter が集め、`Event` に載せて渡す。
//!
//! 設計の詳細と移行の段取りは `docs/plans/done/20260829-core-shell-layers.md`、
//! 今後も効く結論は `docs/CONTEXT.md` の「主要な設計判断」が正。
//!
